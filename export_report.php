if($_SESSION['role'] != 'admin'){
    header("Location: login.php");
    exit();
}

if(!isset($_SESSION['report_preview'])){
    header("Location: generate_reports.php");
    exit();
}

require __DIR__ . '/vendor/autoload.php';

use Dompdf\Dompdf;
use Dompdf\Options;

$preview = $_SESSION['report_preview'];
$sql = $preview['sql'];
$report = $preview['report'];
$columns = $preview['columns'];

$result = mysqli_query($conn, $sql);
$rows = [];

if($result){
    while($row = mysqli_fetch_assoc($result)){
        $rows[] = $row;
    }
}

$title = "Report Preview Export";
if($report == 'traffic') $title = "Traffic Logs Report";
if($report == 'blocked') $title = "Blocked Sites Report";
if($report == 'alerts') $title = "Alert / Notification Logs Report";
if($report == 'support') $title = "Support Issues Report";
if($report == 'users') $title = "Users Report";

$logoPath = __DIR__ . "/images/logo.png";
$logoSrc = "";
if(file_exists($logoPath)){
    $logoData = base64_encode(file_get_contents($logoPath));
    $logoSrc = "data:image/png;base64," . $logoData;
}

$html = '
<html>
<head>
<style>

@page {
    margin: 140px 40px 90px 40px;
}

body{
    font-family: DejaVu Sans, Arial, sans-serif;
