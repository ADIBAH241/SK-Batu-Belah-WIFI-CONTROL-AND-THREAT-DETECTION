if(empty($rows)){
    $html .= '<p>No data available.</p>';
} else {
    $html .= '<table><tr><th>No.</th>';
    foreach($columns as $col){
        $html .= '<th>'.htmlspecialchars($col).'</th>';
    }
    $html .= '</tr>';

    $no = 1;
    foreach($rows as $row){
        $html .= '<tr><td>'.$no++.'</td>';
        foreach($columns as $col){
            $html .= '<td>'.htmlspecialchars((string)($row[$col] ?? '')).'</td>';
        }
        $html .= '</tr>';
    }

    $html .= '</table>';
